#Operators in Python
print("Arithmetic Operators")

'''
*-> Multiplication
/-> Division
//-> Floor Division/Integer Division
%-> Modulus
+-> Addition
- -> Subtraction
**-> Exponentiation/Raise to power
'''
n1 = 10
n2 = 5
print("Multiplication:", n1*n2) #Multiplication
print("Division:", n1/n2) #Division
print("Floor Division:", n1//n2) #Floor Division
print("Modulus:", n1%n2) #Modulus
print("Exponentiation:", n1**n2) #Exponentiation

n1=11
n2=4
print("Multiplication:",n1,"*",n2,"=",n1*n2) #Multiplication
#Formatting Strings -> fstrings
print("Multiplication ->{n1} * {n2} ={n1*n2}")
print("Division ->{n1} / {n2} ={n1/n2}")
print("Floor division ->{n1} // {n2} ={n1//n2}")
print("Modulus ->{n1} % {n2} ={n1%n2}")
